#!/usr/bin/env python3
"""
perf_analysis.py - Phase II performance study (Owner: Aaryan Gera)

Runs every benchmark program on the single-cycle CPU, reads the instruction
mix printed by tb/tb_mips_top.v and compares three organisations:

  * Single-cycle (our design)  : CPI = 1, clock = slowest instruction (lw)
  * Multi-cycle                : CPI depends on instruction class, short clock
  * Ideal 5-stage pipeline     : CPI ~ 1, short clock, + 4 fill cycles, no hazards

Stage delays follow the standard textbook example (Patterson & Hennessy):
  instruction memory 200 ps, register read 100 ps, ALU 200 ps,
  data memory 200 ps, register write 100 ps.
So single-cycle clock = 800 ps (lw path), multi-cycle / pipeline clock = 200 ps.

Writes docs/perf_results.md and docs/images/perf_comparison.png
"""
import os, re, subprocess, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
RTL = " ".join(sorted(glob.glob("rtl/*.v")))
PROGRAMS = ["array_sum", "max_search", "bubble_sort", "factorial", "factorial_hw",
            "string_upper", "full_test", "byte_test"]

T_SINGLE = 800          # ps : IM 200 + RF 100 + ALU 200 + DM 200 + WB 100
T_MULTI = 200           # ps : slowest single stage
MULTI_CPI = {"alu": 4, "load": 5, "store": 4, "branch": 3, "jump": 3, "mul": 4}


def run(prog):
    subprocess.run(f"python3 scripts/mips_asm.py programs/{prog}.s -o programs/build",
                   shell=True, check=True, capture_output=True)
    cmd = (f"iverilog -g2012 -I rtl -o sim/{prog}.vvp "
           f"-P tb_mips_top.IMEM_FILE='\"programs/build/{prog}.hex\"' "
           f"-P tb_mips_top.DMEM_FILE='\"programs/build/{prog}_data.hex\"' "
           f"-P tb_mips_top.VCD_FILE='\"sim/{prog}.vcd\"' tb/tb_mips_top.v {RTL} "
           f"&& vvp -n sim/{prog}.vvp")
    out = subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout
    mix = dict((k, int(v)) for k, v in re.findall(r"(\w+)=(\d+)", out.split("MIX:")[1].splitlines()[0]))
    return mix


def main():
    os.makedirs("sim", exist_ok=True)
    rows = []
    for p in PROGRAMS:
        mix = run(p)
        n = sum(mix.values())
        multi_cycles = sum(MULTI_CPI[k] * v for k, v in mix.items())
        t_single = n * T_SINGLE / 1000          # ns
        t_multi = multi_cycles * T_MULTI / 1000
        t_pipe = (n + 4) * T_MULTI / 1000
        rows.append((p, mix, n, multi_cycles, t_single, t_multi, t_pipe))

    lines = ["# Phase II performance results", "",
             "Generated by `scripts/perf_analysis.py`. Stage delays: IM 200 ps, RF 100 ps, "
             "ALU 200 ps, DM 200 ps, WB 100 ps (single-cycle clock 800 ps, multi-cycle/pipeline clock 200 ps).", "",
             "## Instruction mix", "",
             "| Program | Instr. | ALU | Load | Store | Branch | Jump | Mul |",
             "|---|---|---|---|---|---|---|---|"]
    for p, m, n, *_ in rows:
        lines.append(f"| {p} | {n} | {m['alu']} | {m['load']} | {m['store']} | {m['branch']} | {m['jump']} | {m['mul']} |")
    lines += ["", "## Execution time", "",
              "| Program | Single-cycle cycles (CPI=1) | Single-cycle time (ns) | Multi-cycle cycles | Multi-cycle CPI | Multi-cycle time (ns) | Ideal pipeline time (ns) |",
              "|---|---|---|---|---|---|---|"]
    for p, m, n, mc, ts, tm, tp in rows:
        lines.append(f"| {p} | {n} | {ts:.1f} | {mc} | {mc / n:.2f} | {tm:.1f} | {tp:.1f} |")
    tot_s = sum(r[4] for r in rows); tot_m = sum(r[5] for r in rows); tot_p = sum(r[6] for r in rows)
    fsw = next(r for r in rows if r[0] == "factorial"); fhw = next(r for r in rows if r[0] == "factorial_hw")
    lines += ["", f"Total: single-cycle {tot_s:.1f} ns, multi-cycle {tot_m:.1f} ns "
              f"({tot_s / tot_m:.2f}x faster), ideal pipeline {tot_p:.1f} ns ({tot_s / tot_p:.2f}x faster).", "",
              f"Hardware `mul` vs software multiply (factorial): {fsw[2]} -> {fhw[2]} instructions, "
              f"speed-up {fsw[2] / fhw[2]:.2f}x.", ""]
    os.makedirs("docs/images", exist_ok=True)
    with open("docs/perf_results.md", "w") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    names = [r[0] for r in rows]
    x = range(len(rows)); w = 0.27
    fig, ax = plt.subplots(figsize=(10, 4.2))
    ax.bar([i - w for i in x], [r[4] for r in rows], w, label="Single-cycle (ours)", color="#1f4e79")
    ax.bar(list(x), [r[5] for r in rows], w, label="Multi-cycle", color="#c0504d")
    ax.bar([i + w for i in x], [r[6] for r in rows], w, label="Ideal 5-stage pipeline", color="#4f6228")
    ax.set_xticks(list(x)); ax.set_xticklabels(names, rotation=20, fontsize=9)
    ax.set_ylabel("execution time (ns)"); ax.legend(frameon=False)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(axis="y", color="#e5e5e5"); ax.set_axisbelow(True)
    plt.tight_layout(); plt.savefig("docs/images/perf_comparison.png", dpi=170)


if __name__ == "__main__":
    main()
